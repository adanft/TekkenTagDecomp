#!/usr/bin/env python3
"""Link the PC build: every object undefined.py compiled and gen_data.py assembled, plus a generated stub for each
symbol nobody provides yet. A stub prints its name and stops the program, so running the result shows what the game
needs next. The list of stubs is build/port/stubs.txt.

Usage: port/tools/gen_data.py && port/tools/undefined.py && port/tools/link.py     -> build/port/ttt"""
import re
import subprocess
import sys

from toolchain import BUILD, EXE, GEN, ROOT
from undefined import symbol_addresses

# No host libm: the game is software float (its float results come back in eax), the host's sinf / cosf / sqrtf
# return theirs on the x87 stack, so linking them would give wrong values silently. They stay stubs until the PS2's
# own newlib maths library is built in software float (T23). The host C library still provides the integer-only
# functions it shares with the game (memcpy, strlen, sprintf...); rand / srand go to the PS2's newlib version in T23.
LIBS = []


def undefined_names(stderr):
    """Sorted, unique names of a GNU ld run's `undefined reference` errors."""
    return sorted(set(re.findall(r"undefined reference to `([^']+)'", stderr)))


IMAGE = (0x33F000, 0x1FCDEF0)  # the PS2 program: ELF header, code, data, bss


def resolve(names, addr, chunks):
    """Splits undefined names into linker-script lines and the rest. A name with a PS2 address inside a split data
    chunk (one splat gave no label, or a function's data the C refers to by address) becomes the chunk's label plus
    the offset; a name outside the program (hardware registers, scratchpad, constants splat took for addresses)
    becomes that absolute address (plat_mem.c maps those regions). `addr`: name -> address for names without one in their
    spelling; `chunks`: [(label, address, size)]."""
    script, rest = [], []
    for s in sorted(names):
        a = addr.get(s)
        if a is None:
            m = re.match(r"(?:D|func)_([0-9A-F]+)$", s)
            a = int(m.group(1), 16) if m else None
        if a is None:
            rest.append(s)
            continue
        inside = [(label, a - start) for label, start, size in chunks if start <= a < start + size]
        if inside:
            script.append(f"{s} = {inside[0][0]} + 0x{inside[0][1]:X};")
        elif not IMAGE[0] <= a < IMAGE[1]:
            script.append(f"{s} = 0x{a:X};")
        else:
            rest.append(s)
    return script, rest


def image_script(entries):
    """Linker script that puts the game's data at its PS2 addresses: `entries` are (section, address, size, nobits)
    of the files gen_data.py wrote (image.txt), each in a section `.ttt.<section>`. The initialised ones go into one
    output section `.ttt_data`, the zeroed ones (.sbss, .bss) into `.ttt_bss` (no bytes in the file). At start-up
    plat_mem.c maps EE RAM over the whole range and copies `.ttt_data` into it. Inside an output section
    `.` is an offset from its start; going back (two files overlapping) is refused here rather than by ld."""
    entries = sorted(entries, key=lambda e: e[1])
    end, seen_bss = 0, False
    for name, addr, size, nobits in entries:
        if addr < end:
            raise ValueError(f"image: .ttt.{name} at 0x{addr:08X} overlaps the file before it (ends 0x{end:08X})")
        if seen_bss and not nobits:
            raise ValueError(f"image: initialised .ttt.{name} at 0x{addr:08X} after the zeroed data")
        seen_bss |= nobits
        end = addr + size
    out = ["/* Generated by port/tools/link.py: the game's data at its PS2 addresses (gen_data.py, image.txt). */",
           "SECTIONS", "{"]
    for group, nobits, extra in ((".ttt_data", False, ""), (".ttt_bss", True, " (NOLOAD)")):
        part = [e for e in entries if e[3] == nobits]
        if not part:
            continue
        base, tag = part[0][1], group[5:]
        out.append(f"  {group} 0x{base:08X}{extra} :")
        out.append("  {")
        out.append(f"    __ttt_{tag}_start = ABSOLUTE(.);")
        for name, addr, size, _ in part:
            if addr != base:
                out.append(f"    . = 0x{addr - base:X};")
            out.append(f"    *(.ttt.{name})")
        out.append(f"    __ttt_{tag}_end = ABSOLUTE(.);")
        out.append("  }")
    out += ["}", "INSERT AFTER .bss;"]
    return "\n".join(out) + "\n"


def read_image(path):
    """Entries of gen_data.py's image.txt for image_script."""
    out = []
    for l in path.read_text().splitlines():
        name, addr, size, kind = l.split()
        out.append((name, int(addr, 16), int(size, 16), kind == "nobits"))
    return out


def stub_source(names):
    """C source of one stub per name: it reports the name and exits (code 3). With TTT_STUB_RETURN=<n> in the
    environment a stub reports its first call and returns n instead, to see how far the game's start gets past the
    missing functions; one called a million times (a retry loop) stops the program."""
    lines = ["/* Generated by port/tools/link.py: one stub per symbol the PC build does not provide yet. */",
             "extern int printf(const char *, ...);", "extern void exit(int);", "extern char *getenv(const char *);",
             "extern int atoi(const char *);", "extern int fflush(void *);",
             "extern void Port_Hit(const char *);  /* plat_stub.c: the headless report lists what was hit */",
             "static int missing(const char *n, int *calls) {",
             "    static int mode = -1, ret;",
             "    if (mode < 0) { const char *e = getenv(\"TTT_STUB_RETURN\"); mode = e != 0; ret = e ? atoi(e) : 0; }",
             '    if (!mode) { printf("ttt: not implemented yet: %s\\n", n); exit(3); }',
             "    Port_Hit(n);",
             '    if ((*calls)++ == 0) { printf("ttt: stub %s returns %d\\n", n, ret); fflush(0); }',
             '    if (*calls == 1000000) { printf("ttt: stub %s called %d times: stopping\\n", n, *calls); exit(3); }',
             "    return ret;", "}"]
    lines += [f'int {s}(void) {{ static int n; return missing("{s}", &n); }}' for s in names]
    return "\n".join(lines) + "\n"


def link(objs, extra):
    # --wrap=main: plat_main.c runs the game's main on a stack in EE RAM, as on the PS2.
    cmd = (["gcc", "-m32", "-no-pie", "-w", "-Wl,--wrap=main", "-o", str(EXE)] + extra + objs + LIBS +
           [f"-Wl,-Map={EXE}.map"])
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)


def main():
    listing = BUILD / "objects.txt"
    if not listing.exists():
        sys.exit("link: run port/tools/undefined.py first")
    objs = [l for l in listing.read_text().splitlines() if l]
    image = GEN / "image.ld"
    image.write_text(image_script(read_image(GEN / "image.txt")))
    r = link(objs, [f"-Wl,-T,{image}"])  # first pass: ask the linker what nobody provides (the host C library included)
    chunks = []
    for l in (GEN / "chunks.txt").read_text().splitlines():
        label, start, size = l.split()
        chunks.append((label, int(start, 16), int(size, 16)))
    script, need = resolve(undefined_names(r.stderr), symbol_addresses(), chunks)
    names = GEN / "symbols.ld"
    names.write_text("/* Generated by port/tools/link.py: game names placed by their PS2 address. */\n" +
                     "".join(l + "\n" for l in script))
    stubs = GEN / "stubs.c"
    stubs.parent.mkdir(parents=True, exist_ok=True)
    stubs.write_text(stub_source(need))
    (BUILD / "stubs.txt").write_text("".join(s + "\n" for s in need))
    stub_obj = BUILD / "stubs.o"
    c = subprocess.run(["gcc", "-m32", "-c", "-w", "-fno-builtin", str(stubs), "-o", str(stub_obj)],
                       capture_output=True, text=True)
    if c.returncode:
        sys.exit(f"link: stubs do not compile: {c.stderr[:400]}")
    r = link(objs, [f"-Wl,-T,{image}", str(stub_obj), str(names)])
    errs = [l for l in r.stderr.splitlines() if "multiple definition" in l or "undefined reference" in l or "rror" in l]
    state = f"OK -> {EXE.relative_to(ROOT)}" if r.returncode == 0 else "FAILED"
    print(f"link: {len(objs)} objects, {len(script)} names placed by address, {len(need)} stubs; link {state}; "
          f"{len(errs)} error lines")
    for l in errs[:20]:
        print("  " + l[-200:])
    if r.returncode:
        sys.exit(1)


if __name__ == "__main__":
    main()
