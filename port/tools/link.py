#!/usr/bin/env python3
"""Link the PC build: every object undefined.py compiled, the game's data layout (port/tools/data_layout.txt: names
placed at their PS2 addresses, the table plat_data.c loads the data from the user's disc with; no game data is
linked in), plus a generated stub for each symbol nobody provides yet. A stub prints its name and stops the program,
so running the result shows what the game needs next. The list of stubs is build/port/stubs.txt.

Usage: port/tools/undefined.py && port/tools/link.py     -> build/port/ttt"""
import re
import subprocess
import sys

from toolchain import BUILD, EXE, GEN, ROOT
from undefined import symbol_addresses

# No host libm: the game is software float (its float results come back in eax), the host's sinf / cosf / sqrtf
# return theirs on the x87 stack, so linking them would give wrong values silently. They stay stubs until the PS2's
# own newlib maths library is built in software float (T23). The host C library still provides the integer-only
# functions it shares with the game (memcpy, strlen, sprintf...); rand / srand go to the PS2's newlib version in T23.
LIBS = ["-pthread"]  # the GS raster threads (TTT_GS_THREADS, gs_core.c)


def undefined_names(stderr):
    """Sorted, unique names of a GNU ld run's `undefined reference` errors."""
    return sorted(set(re.findall(r"undefined reference to `([^']+)'", stderr)))


IMAGE = (0x33F000, 0x1FCDEF0)  # the PS2 program: ELF header, code, data, bss
LAYOUT = ROOT / "port/tools/data_layout.txt"


def resolve(names, addr, spans):
    """Splits undefined names into linker-script lines and the rest. A name whose PS2 address lies in the game's data
    (`spans`: [(address, size)] of the layout's ranges and zeroed files) becomes that address: the data is loaded
    there from the user's disc at start (plat_data.c); so does a name outside the program (hardware registers,
    scratchpad, constants splat took for addresses: plat_mem.c maps those regions). `addr`: name -> address for
    names without one in their spelling. Names of the program's code range with no definition are the rest (stubs)."""
    script, rest = [], []
    for s in sorted(names):
        a = addr.get(s)
        if a is None:
            m = re.match(r"(?:D|func)_([0-9A-F]+)$", s)
            a = int(m.group(1), 16) if m else None
        if a is None:
            rest.append(s)
            continue
        if any(start <= a < start + size for start, size in spans) or not IMAGE[0] <= a < IMAGE[1]:
            script.append(f"{s} = 0x{a:X};")
        else:
            rest.append(s)
    return script, rest


def read_layout(path=LAYOUT):
    """port/tools/data_layout.txt (make_layout.py) as a dict: ranges [(addr, size)], bss (addr, size), nobits
    [(addr, size)], words [(addr, name, addend)], zeros [addr], labels {name: addr}, payload (size, sha1 hex),
    elf (name, size, sha1 hex)."""
    out = {"ranges": [], "nobits": [], "words": [], "zeros": [], "labels": {}}
    for l in path.read_text().splitlines():
        f = l.split()
        if not f or f[0].startswith("#"):
            continue
        k = f[0]
        if k == "range" or k == "nobits":
            out[k + "s" if k == "range" else k].append((int(f[1], 16), int(f[2], 16)))
        elif k == "bss":
            out["bss"] = (int(f[1], 16), int(f[2], 16))
        elif k == "word":
            out["words"].append((int(f[1], 16), f[2], int(f[3])))
        elif k == "zero":
            out["zeros"].append(int(f[1], 16))
        elif k == "label":
            out["labels"][f[1]] = int(f[2], 16)
        elif k == "payload":
            out["payload"] = (int(f[1], 16), f[2])
        elif k == "elf":
            out["elf"] = (f[1], int(f[2]), f[3])
        else:
            raise ValueError(f"{path.name}: unknown line: {l}")
    return out


def image_script(layout):
    """Linker script naming the bounds of the game's data at its PS2 addresses: no byte of it is in the program
    (plat_data.c loads it from the disc into EE RAM, plat_mem.c maps EE RAM over the whole range)."""
    ranges = sorted(layout["ranges"])
    end = 0
    for a, n in ranges:
        if a < end:
            raise ValueError(f"layout: range 0x{a:08X} overlaps the one before it (ends 0x{end:08X})")
        end = a + n
    lo, size = layout["bss"]
    if lo < end:
        raise ValueError(f"layout: initialised data up to 0x{end:08X} after the zeroed data at 0x{lo:08X}")
    return ("/* Generated by port/tools/link.py: bounds of the game's data at its PS2 addresses (data_layout.txt). */\n"
            f"__ttt_data_start = 0x{ranges[0][0]:08X};\n__ttt_data_end = 0x{end:08X};\n"
            f"__ttt_bss_start = 0x{lo:08X};\n__ttt_bss_end = 0x{lo + size:08X};\n")


def data_table(layout, keep=None):
    """C source of the tables plat_data.c loads the game's data with: the ranges to copy from the disc's executable,
    the payload's size and SHA-1, and the words to rewrite (name + addend, filled in by the linker; 0). `keep`: the
    names whose words stay (None: all); a name the linker places at its own PS2 address is left out, the disc's word
    being that address already."""
    words = [w for w in layout["words"] if keep is None or w[1] in keep]
    size, sha1 = layout["payload"]
    lines = ["/* Generated by port/tools/link.py from port/tools/data_layout.txt: no game data, addresses only. */",
             "#include <stdint.h>"]
    lines += [f"extern char {n}[];" for n in sorted({w[1] for w in words})]
    lines.append("const uint32_t gPortDataRanges[][2] = {")
    lines += [f"    {{0x{a:08X}u, 0x{n:X}u}}," for a, n in layout["ranges"]]
    lines.append("};")
    lines.append(f"const uint32_t gPortDataRangeN = {len(layout['ranges'])};")
    fixes = sorted([(a, f"(uint32_t)(uintptr_t){n} + ({d})") for a, n, d in words] + [(a, "0") for a in layout["zeros"]])
    lines.append("const uint32_t gPortDataFix[][2] = {")
    lines += [f"    {{0x{a:08X}u, {v}}}," for a, v in fixes] or ["    {0, 0},"]
    lines.append("};")
    lines.append(f"const uint32_t gPortDataFixN = {len(fixes)};")
    lines.append(f"const uint32_t gPortDataSize = 0x{size:X}u;")
    lines.append("const uint8_t gPortDataSha1[20] = {" + ", ".join(f"0x{sha1[i:i + 2]}" for i in range(0, 40, 2)) + "};")
    elf = layout["elf"]
    lines.append("const uint8_t gPortElfSha1[20] = {" + ", ".join(f"0x{elf[2][i:i + 2]}" for i in range(0, 40, 2)) + "};")
    lines.append(f"const uint32_t gPortElfSize = {elf[1]}u;")
    return "\n".join(lines) + "\n"


def stub_source(names):
    """C source of one stub per name: it reports the name and exits (code 3). With TTT_STUB_RETURN=<n> in the
    environment a stub reports its first call and returns n instead, to see how far the game's start gets past the
    missing functions; one called a million times (a retry loop) stops the program."""
    lines = ["/* Generated by port/tools/link.py: one stub per symbol the PC build does not provide yet. */",
             "extern int printf(const char *, ...);", "extern void exit(int);", "extern char *getenv(const char *);",
             "extern int atoi(const char *);", "extern int fflush(void *);",
             "extern void Port_Hit(const char *);  /* plat_stub.c: the headless report lists what was hit */",
             "static int missing(const char *n, int *calls) {",
             "    static int mode = -1, ret;",
             "    if (mode < 0) { const char *e = getenv(\"TTT_STUB_RETURN\"); mode = e != 0; ret = e ? atoi(e) : 0; }",
             '    if (!mode) { printf("ttt: not implemented yet: %s\\n", n); exit(3); }',
             "    Port_Hit(n);",
             '    if ((*calls)++ == 0) { printf("ttt: stub %s returns %d\\n", n, ret); fflush(0); }',
             '    if (*calls == 1000000) { printf("ttt: stub %s called %d times: stopping\\n", n, *calls); exit(3); }',
             "    return ret;", "}"]
    lines += [f'int {s}(void) {{ static int n; return missing("{s}", &n); }}' for s in names]
    return "\n".join(lines) + "\n"


def link(objs, extra):
    # --wrap=main: plat_main.c runs the game's main on a stack in EE RAM, as on the PS2.
    # -z now and --wrap=printf / sprintf / memcpy / memset: nothing of the C library (lazy binding, its internal calls)
    # runs on the EE stack, whose stale words a state holds and the game reads in places (port/src/plat_libc.c, T27).
    cmd = (["gcc", "-m32", "-no-pie", "-w", "-Wl,--wrap=main", "-Wl,-z,now"] +
           [f"-Wl,--wrap={f}" for f in ("printf", "sprintf", "memcpy", "memset")] + ["-o", str(EXE)] + extra + objs + LIBS +
           [f"-Wl,-Map={EXE}.map"])
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)


def compile_c(src, obj, *flags):
    c = subprocess.run(["gcc", "-m32", "-c", "-w", "-fno-builtin", *flags, str(src), "-o", str(obj)],
                       capture_output=True, text=True)
    if c.returncode:
        sys.exit(f"link: {src.name} does not compile: {c.stderr[:400]}")


def main():
    listing = BUILD / "objects.txt"
    if not listing.exists():
        sys.exit("link: run port/tools/undefined.py first")
    objs = [l for l in listing.read_text().splitlines() if l]
    layout = read_layout()
    GEN.mkdir(parents=True, exist_ok=True)
    image = GEN / "image.ld"
    image.write_text(image_script(layout))
    table, table_obj = GEN / "data_table.c", BUILD / "data_table.o"
    table.write_text(data_table(layout))
    compile_c(table, table_obj, "-fno-pic")
    # first pass: ask the linker what nobody provides (the host C library included)
    r = link(objs, [str(image), str(table_obj)])
    addr = dict(symbol_addresses(), **layout["labels"])
    script, need = resolve(undefined_names(r.stderr), addr, layout["ranges"] + layout["nobits"])
    names = GEN / "symbols.ld"
    names.write_text("/* Generated by port/tools/link.py: game names placed by their PS2 address. */\n" +
                     "".join(l + "\n" for l in script))
    placed = {l.split(" = ")[0] for l in script}
    table.write_text(data_table(layout, keep={w[1] for w in layout["words"]} - placed))
    compile_c(table, table_obj, "-fno-pic")
    stubs = GEN / "stubs.c"
    stubs.write_text(stub_source(need))
    (BUILD / "stubs.txt").write_text("".join(s + "\n" for s in need))
    stub_obj = BUILD / "stubs.o"
    compile_c(stubs, stub_obj)
    r = link(objs, [str(image), str(table_obj), str(stub_obj), str(names)])
    errs = [l for l in r.stderr.splitlines() if "multiple definition" in l or "undefined reference" in l or "rror" in l]
    state = f"OK -> {EXE.relative_to(ROOT)}" if r.returncode == 0 else "FAILED"
    print(f"link: {len(objs)} objects, {len(script)} names placed by address, {len(need)} stubs; link {state}; "
          f"{len(errs)} error lines")
    for l in errs[:20]:
        print("  " + l[-200:])
    if r.returncode:
        sys.exit(1)
    write_symbols(addr)


def symbol_table(nm_out, addr):
    """build/port/ttt.syms for the crash report (port/src/plat_crash.c): the program's code symbols in address order,
    "<host address> <PS2 address or 00000000> <name>" (the PS2 address from the decompilation's names: func_XXXXXXXX
    or the symbol list). The program's own symbols only: names and addresses, no data."""
    out = []
    for l in nm_out.splitlines():
        f = l.split()
        if len(f) != 3 or f[1] not in "tTwW":
            continue
        a, name = int(f[0], 16), f[2]
        m = re.match(r"func_([0-9A-F]{8})(?:\.|$)", name)
        ps2 = int(m.group(1), 16) if m else addr.get(name, 0)
        out.append(f"{a:08x} {ps2 if 0 < ps2 < 0x02000000 else 0:08x} {name}\n")
    return "".join(out)


def write_symbols(addr):
    nm = subprocess.run(["nm", "-n", "--defined-only", str(EXE)], capture_output=True, text=True, check=True).stdout
    path = EXE.with_name(EXE.name + ".syms")
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(symbol_table(nm, addr))
    tmp.replace(path)


if __name__ == "__main__":
    main()
