#!/usr/bin/env python3
"""Link the PC build: every object undefined.py compiled and gen_data.py assembled, plus a generated stub for each
symbol nobody provides yet. A stub prints its name and stops the program, so running the result shows what the game
needs next. The list of stubs is build/port/stubs.txt.

Usage: port/tools/gen_data.py && port/tools/undefined.py && port/tools/link.py     -> build/port/ttt"""
import re
import subprocess
import sys

from toolchain import BUILD, EXE, GEN, ROOT
from undefined import symbol_addresses

# No host libm: the game is software float (its float results come back in eax), the host's sinf / cosf / sqrtf
# return theirs on the x87 stack, so linking them would give wrong values silently. They stay stubs until the PS2's
# own newlib maths library is built in software float (T23). The host C library still provides the integer-only
# functions it shares with the game (memcpy, strlen, sprintf...); rand / srand go to the PS2's newlib version in T23.
LIBS = []


def undefined_names(stderr):
    """Sorted, unique names of a GNU ld run's `undefined reference` errors."""
    return sorted(set(re.findall(r"undefined reference to `([^']+)'", stderr)))


IMAGE = (0x33F000, 0x1FCDEF0)  # the PS2 program: ELF header, code, data, bss


def resolve(names, addr, chunks):
    """Splits undefined names into linker-script lines and the rest. A name with a PS2 address inside a split data
    chunk (one splat gave no label, or a function's data the C refers to by address) becomes the chunk's label plus
    the offset; a name outside the program (hardware registers, scratchpad, constants splat took for addresses)
    becomes that absolute address (T22 maps those regions). `addr`: name -> address for names without one in their
    spelling; `chunks`: [(label, address, size)]."""
    script, rest = [], []
    for s in sorted(names):
        a = addr.get(s)
        if a is None:
            m = re.match(r"(?:D|func)_([0-9A-F]+)$", s)
            a = int(m.group(1), 16) if m else None
        if a is None:
            rest.append(s)
            continue
        inside = [(label, a - start) for label, start, size in chunks if start <= a < start + size]
        if inside:
            script.append(f"{s} = {inside[0][0]} + 0x{inside[0][1]:X};")
        elif not IMAGE[0] <= a < IMAGE[1]:
            script.append(f"{s} = 0x{a:X};")
        else:
            rest.append(s)
    return script, rest


def stub_source(names):
    """C source of one stub per name: it reports the name and exits."""
    lines = ["/* Generated by port/tools/link.py: one stub per symbol the PC build does not provide yet. */",
             "extern int printf(const char *, ...);", "extern void exit(int);",
             'static void missing(const char *n) { printf("ttt: not implemented yet: %s\\n", n); exit(3); }']
    lines += [f'void {s}(void) {{ missing("{s}"); }}' for s in names]
    return "\n".join(lines) + "\n"


def link(objs, extra):
    cmd = ["gcc", "-m32", "-no-pie", "-w", "-o", str(EXE)] + extra + objs + LIBS + [f"-Wl,-Map={EXE}.map"]
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)


def main():
    listing = BUILD / "objects.txt"
    if not listing.exists():
        sys.exit("link: run port/tools/undefined.py first")
    objs = [l for l in listing.read_text().splitlines() if l]
    r = link(objs, [])  # first pass: ask the linker what nobody provides (the host C library included)
    chunks = []
    for l in (GEN / "chunks.txt").read_text().splitlines():
        label, start, size = l.split()
        chunks.append((label, int(start, 16), int(size, 16)))
    script, need = resolve(undefined_names(r.stderr), symbol_addresses(), chunks)
    names = GEN / "symbols.ld"
    names.write_text("/* Generated by port/tools/link.py: game names placed by their PS2 address. */\n" +
                     "".join(l + "\n" for l in script))
    stubs = GEN / "stubs.c"
    stubs.parent.mkdir(parents=True, exist_ok=True)
    stubs.write_text(stub_source(need))
    (BUILD / "stubs.txt").write_text("".join(s + "\n" for s in need))
    stub_obj = BUILD / "stubs.o"
    c = subprocess.run(["gcc", "-m32", "-c", "-w", "-fno-builtin", str(stubs), "-o", str(stub_obj)],
                       capture_output=True, text=True)
    if c.returncode:
        sys.exit(f"link: stubs do not compile: {c.stderr[:400]}")
    r = link(objs, [str(stub_obj), str(names)])
    errs = [l for l in r.stderr.splitlines() if "multiple definition" in l or "undefined reference" in l or "rror" in l]
    state = f"OK -> {EXE.relative_to(ROOT)}" if r.returncode == 0 else "FAILED"
    print(f"link: {len(objs)} objects, {len(script)} names placed by address, {len(need)} stubs; link {state}; "
          f"{len(errs)} error lines")
    for l in errs[:20]:
        print("  " + l[-200:])
    if r.returncode:
        sys.exit(1)


if __name__ == "__main__":
    main()
